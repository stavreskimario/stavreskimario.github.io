// Run with node tests/la-travel-core.cjs (no dependencies).
const assert = require('node:assert/strict');
const C = require('../la-trip/travel-core.js');
const iso = (time,zone) => new Date(C.instant(time,zone)).toISOString();
assert.equal(iso('2026-12-20T10:00','Australia/Melbourne'),'2026-12-19T23:00:00.000Z');
assert.equal(iso('2026-12-25T14:00','America/Los_Angeles'),'2026-12-25T22:00:00.000Z');
assert.equal(iso('2026-12-29T08:00','Australia/Melbourne'),'2026-12-28T21:00:00.000Z');
assert.throws(()=>C.instant('2026-03-08T02:30','America/Los_Angeles'),/does not exist/);
assert.throws(()=>C.instant('2026-11-01T01:30','America/Los_Angeles'),/occurs twice/);
assert.throws(()=>C.instant('2026-02-31T14:00','UTC'),/date/);
assert.throws(()=>C.schedule({start:'2026-12-20T12:00',end:'2026-12-20T11:00'}),/after/);
assert.throws(()=>C.schedule({travel:-1}),/estimate/);
assert.throws(()=>C.schedule({end:'2026-12-21T10:00'}),/start time/);
assert.equal(C.cents('0.29'),29);
assert.equal(C.cents('100.1'),10010);
assert.throws(()=>C.cents('1.999'));
assert.throws(()=>C.cents('-1'));
assert.throws(()=>C.cents('Infinity'));
const expense = (fields={})=>({id:'e1',title:'Tickets',amount:10001,currency:'USD',state:'paid',payer:'Mario',marioShare:50,date:'2026-12-23',category:'Activities',event:'',note:'',actualAud:null,...fields});
let data=C.companion({...C.defaults(),rate:1.5,budget:100000,expenses:[expense()]});
assert.deepEqual(C.totals(data),{paid:15002,planned:0,balance:-7501,unconverted:0,native:{AUD:{paid:0,planned:0},USD:{paid:10001,planned:0}},remaining:84998});
data.expenses.push(expense({id:'e2',currency:'AUD',amount:3000,state:'planned'}));
assert.equal(C.totals(data).planned,3000);
assert.equal(C.totals(data).paid,15002);
data.expenses[1].state='paid';
assert.equal(C.totals(data).planned,0);
assert.equal(C.totals(data).paid,18002);
data.settlements.push({id:'s1',from:'Andreas',amount:9001,date:'2026-12-24',note:''});
assert.equal(C.totals(data).balance,0);
assert.equal(C.totals(data).paid,18002,'repayments must not inflate spending');
data.expenses[0].actualAud=14000;data.rate=2;
assert.equal(C.totals(data).paid,17000,'actual AUD charge must ignore rate changes');
data.rate=null;data.expenses[0].actualAud=null;
assert.equal(C.totals(data).unconverted,1);
assert.equal(C.totals(data).paid,3000,'unknown conversion must never become a guessed rate');
for(const bad of [NaN,Infinity,0,-1])assert.throws(()=>C.companion({...C.defaults(),rate:bad}));
assert.throws(()=>C.companion({...C.defaults(),expenses:[expense({marioShare:101})]}));
assert.throws(()=>C.companion({...C.defaults(),expenses:[expense({state:'planned',actualAud:100})]}));
assert.throws(()=>C.companion({...C.defaults(),ideas:[{id:'x',title:'Unsafe',source:'javascript:alert(1)'}]}));
assert.throws(()=>C.companion({...C.defaults(),ideas:[{id:'x',title:'One'},{id:'x',title:'Two'}]}));
const events=[{id:'flight-1',title:'Melbourne → LA; <flight>',location:'MEL, Australia',time:'See ticket',note:'Line one\nLine two',status:'plan',source:'',schedule:C.schedule({start:'2026-12-20T10:00',zone:'Australia/Melbourne',end:'2026-12-20T06:00',endZone:C.ZONE})},{id:'idea-2',title:'A flexible café '.repeat(8),location:'Los Angeles',time:'Afternoon',note:'Not booked',status:'proposed'}];
const days=[{date:20,events}];
const ics=C.calendar(days,null,new Date('2026-10-01T00:00:00Z'));
assert.equal(ics.count,2);assert.equal(ics.floating,1);
assert(ics.content.includes('DTSTART:20261219T230000Z'));
assert(ics.content.includes('DTEND:20261220T140000Z'));
assert(ics.content.includes('DTSTART;VALUE=DATE:20261220'));
assert(ics.content.includes('DTEND;VALUE=DATE:20261221'));
assert(ics.content.includes('CLASS:PRIVATE'));
assert(ics.content.includes('SUMMARY:Melbourne → LA\\; <flight>'));
for(const line of ics.content.split('\r\n'))assert(Buffer.byteLength(line)<=75,'calendar lines must fold on UTF-8 byte boundaries');
assert.equal(C.calendar(days,['flight-1']).count,1);
assert.equal(C.calendar(days,[]).count,0);
assert.equal(C.upcoming(days,Date.parse('2026-12-19T22:00Z')).event.id,'flight-1');
assert.equal(C.upcoming(days,Date.parse('2026-12-20T15:00Z')),null);
const hotel={id:'hotel',type:'hotel',status:'booked',schedule:C.schedule({start:'2026-12-20T15:00',end:'2026-12-28T11:00'})};
const game={id:'game',type:'ball',status:'plan',schedule:C.schedule({start:'2026-12-25T14:00'})};
assert.equal(C.upcoming([{date:20,events:[hotel,game]}],Date.parse('2026-12-24T18:00Z')).event.id,'game');
const before={schedule:C.schedule({start:'2026-12-23T15:00',end:'2026-12-23T16:00'})};
const after={schedule:C.schedule({start:'2026-12-23T16:30',travel:30,buffer:15})};
assert(C.timingWarning(before,after).includes('15 more minutes'));
const route=new URL(C.routeUrl(['A & B','C / D','E | F'],'walking'));
assert.equal(route.searchParams.get('origin'),'A & B');assert.equal(route.searchParams.get('waypoints'),'C / D');assert.equal(route.searchParams.get('destination'),'E | F');assert.equal(route.searchParams.get('travelmode'),'walking');
assert.throws(()=>C.routeUrl(['A']));assert.throws(()=>C.routeUrl(['a','b','c','d','e','f']));
assert.deepEqual(C.draftText('Coffee | 24 Dec | Afternoon | Downtown | https://example.com')[0],{title:'Coffee',day:24,time:'Afternoon',location:'Downtown',source:'https://example.com/',note:''});
console.log('Travel core: timezone/DST, currency/splits/repayments, validation, calendar, routes and import checks passed.');
