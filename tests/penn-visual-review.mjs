import assert from 'node:assert/strict';
import * as THREE from 'three';
import { getMaterialReport, sampleVisuals } from '../penn-station-1935/src/visual-review.mjs';

const root = new THREE.Group(), waiting = new THREE.Group(), other = new THREE.Group();
waiting.name = 'waiting'; other.name = 'trains'; root.add(waiting, other);
const geometry = new THREE.BufferGeometry();
geometry.setAttribute('position', new THREE.Float32BufferAttribute([-1,-1,0, 1,-1,0, 0,1,0],3));
geometry.setAttribute('uv', new THREE.Float32BufferAttribute([0,0, 1,0, .5,1],2));
geometry.setAttribute('uv1', new THREE.Float32BufferAttribute([.2,.3, .8,.3, .5,.9],2));
geometry.computeVertexNormals(); geometry.computeBoundingBox(); geometry.computeBoundingSphere();
const ao = new THREE.DataTexture(new Uint8Array(4*8*4),4,8); ao.channel=1; ao.flipY=true;
ao.wrapS=THREE.RepeatWrapping; ao.wrapT=THREE.ClampToEdgeWrapping;
ao.matrix.setUvTransform(1.2,.1,1,1,0,0,0); ao.matrixAutoUpdate=false;
const lightmap = new THREE.DataTexture(new Uint8Array(2*2*4),2,2); lightmap.channel=0;
const material = new THREE.MeshPhysicalMaterial({name:'VisualReviewFixture',side:THREE.DoubleSide,transmission:.85,aoMap:ao,lightMap:lightmap});
material.userData.sky_illumination='fixture-order.webp'; material.userData.sky_illumination_scale=2;
const mesh = new THREE.Mesh(geometry,material); mesh.scale.set(2,1,1); waiting.add(mesh);
const foreign = new THREE.InstancedMesh(geometry,material,1); foreign.raycast=()=>{throw Error('Requested-zone ray touched unrelated instances');}; other.add(foreign);
const camera = new THREE.PerspectiveCamera(50,1,.1,100); camera.position.set(0,0,5); camera.lookAt(0,0,0);
root.updateMatrixWorld(true); camera.updateMatrixWorld(true); camera.updateProjectionMatrix();
const renderer={domElement:{width:200,height:200,getBoundingClientRect:()=>({left:10,top:20,width:100,height:100})}};
const before={world:mesh.matrixWorld.elements.slice(),camera:camera.matrixWorld.elements.slice(),texture:ao.matrix.elements.slice(),positions:Array.from(geometry.attributes.position.array),side:material.side};
root.updateMatrixWorld=camera.updateMatrixWorld=mesh.updateMatrixWorld=()=>{throw Error('Review helper updated a mounted matrix');};
ao.updateMatrix=()=>{throw Error('Review helper updated a texture matrix');};
const materials=getMaterialReport(root); assert.equal(materials.length,1); assert.equal(materials[0].meshes,2);
assert.deepEqual(materials[0].zones,['waiting','trains']); assert.equal(materials[0].transmission,.85);
assert.deepEqual([materials[0].ao.width,materials[0].ao.height,materials[0].ao.channel],[4,8,1]);
assert(!JSON.stringify(materials).includes('data:image')); assert.equal(materials[0].ao.data,undefined);
const result=sampleVisuals(root,camera,renderer,[{label:'centre',x:60,y:70},{x:-1,y:-1}]);
assert.equal(result.zone,'waiting'); assert.equal(result.samples[0].material.name,'VisualReviewFixture');
assert(result.samples[0].uv1.every((v,i)=>Math.abs(v-[.5,.6][i])<1e-6));
assert(result.samples[0].mappedAOuv.every((v,i)=>Math.abs(v-[.7,.3][i])<1e-6));
assert(result.samples[0].mappedLightmapUV.every((v,i)=>Math.abs(v-.5)<1e-6));
assert.deepEqual(result.samples[0].faceNormalWorld,[0,0,1]); assert.equal(result.samples[1].miss,'Outside canvas');
assert.equal(sampleVisuals(root,camera,renderer,[],{zone:'missing'}).error,'Requested mounted zone is unavailable');
assert.deepEqual(before,{world:mesh.matrixWorld.elements.slice(),camera:camera.matrixWorld.elements.slice(),texture:ao.matrix.elements.slice(),positions:Array.from(geometry.attributes.position.array),side:material.side});
assert.deepEqual(getMaterialReport(null),[]); assert.equal(sampleVisuals(null,camera,renderer,[]),null);
console.log('PASS readonly material metadata, scoped actual rays, UV channels/wrap/flip, no matrix/material mutation');
